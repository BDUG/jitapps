"""Generate SDK contracts from protocol.json; --check detects stale artifacts."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def type_name(schema, language):
    if 'anyOf' in schema:
        return (' | ' if language == 'ts' else ' | ').join(type_name(s, language) for s in schema['anyOf'])
    if 'const' in schema:
        return json.dumps(schema['const']) if language == 'ts' else f"Literal[{schema['const']!r}]"
    if 'enum' in schema:
        return ' | '.join(json.dumps(v) for v in schema['enum']) if language == 'ts' else f"Literal[{', '.join(repr(v) for v in schema['enum'])}]"
    kind = schema.get('type')
    if kind == 'array':
        inner = type_name(schema.get('items', {}), language)
        return f'Array<{inner}>' if language == 'ts' else f'list[{inner}]'
    if language == 'ts' and kind == 'object' and schema.get('properties'):
        required = schema.get('required', [])
        return '{ ' + '; '.join(f'{json.dumps(k)}{"" if k in required else "?"}: {type_name(v, language)}' for k, v in schema['properties'].items()) + ' }'
    return ({'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null','object':'Record<string, unknown>'} if language == 'ts' else {'string':'str','integer':'int','number':'float','boolean':'bool','null':'None','object':'dict[str, Any]'}).get(kind, 'unknown' if language == 'ts' else 'Any')


def outputs():
    sdk = json.loads((ROOT / 'protocol.json').read_text())['sdk']
    schemas = sdk['contracts']
    js = '// Generated by scripts/generate_contracts.py. Do not edit.\nmodule.exports = ' + json.dumps(sdk, indent=2) + ';\n'
    py = '# Generated by scripts/generate_contracts.py. Do not edit.\nfrom typing import Any, Literal, TypedDict\n\nSCHEMAS = ' + repr(sdk) + '\n\n'
    ts = '// Generated by scripts/generate_contracts.py. Do not edit.\n'
    rs = '// Generated by scripts/generate_contracts.py. Do not edit.\nuse serde::{Deserialize, Serialize};\n'
    rs += 'pub const CONTRACTS: &str = r###"' + json.dumps(sdk) + '"###;\n'
    for name, schema in schemas.items():
        ts += f'export type {name} = {type_name(schema, "ts")};\n'
        py += f'class _{name}Required(TypedDict):\n'
        for key, field in schema['properties'].items():
            if key in schema['required']:
                py += f'    {key}: {type_name(field, "py")}\n'
        py += f'\nclass {name}(_{name}Required, total=False):\n'
        if all(key in schema['required'] for key in schema['properties']):
            py += '    pass\n'
        rs += '#[derive(Clone, Debug, Serialize, Deserialize)]\n#[serde(deny_unknown_fields)]\n' + f'pub struct {name} {{\n'
        for key, field in schema['properties'].items():
            required = key in schema['required']
            py_type = type_name(field, 'py')
            if not required:
                py += f'    {key}: {py_type}\n'
            rust_type = {'string':'String','integer':'u64','boolean':'bool'}.get(field.get('type'), 'serde_json::Value')
            if isinstance(field.get('const'),str) or field.get('enum') and all(isinstance(v,str) for v in field['enum']):
                rust_type = 'String'
            if key == 'events' and name == 'ModelRequest':
                rust_type = 'Vec<AgentEvent>'
            if key == 'tools' and name == 'ModelRequest':
                rust_type = 'Vec<ToolDefinition>'
            if key == 'error' and name == 'ToolResult':
                rust_type = 'AgentError'
            rust_key = ''.join('_' + ch.lower() if ch.isupper() else ch for ch in key)
            if rust_key != key:
                rs += f'    #[serde(rename = "{key}")]\n'
            if not required:
                rs += '    #[serde(default, skip_serializing_if = "Option::is_none")]\n'
                rust_type = f'Option<{rust_type}>'
            rs += f'    pub {rust_key}: {rust_type},\n'
        py += '\n'
        rs += '}\n'
    return {'javascript/contracts-data.js':js, 'javascript/contracts.d.ts':ts, 'python/contracts_data.py':py.rstrip()+'\n', 'rust/src/contracts_data.rs':rs}


if __name__ == '__main__':
    check = argparse.ArgumentParser()
    check.add_argument('--check', action='store_true')
    args = check.parse_args()
    for relative, content in outputs().items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit('Stale generated contract: ' + relative)
        else:
            path.write_text(content)
